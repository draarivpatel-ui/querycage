const CODE = QUERYCAGE_ERROR_CODES;

class QueryCageError extends Error {
  constructor(code, detail, param) {
    const message = typeof detail === 'string' && detail.length > 0 ? detail : code;
    super(message);
    this.name = 'QueryCageError';
    this.code = typeof code === 'string' ? code : QUERYCAGE_ERROR_CODES.INVALID_INPUT;
    this.detail = message;
    if (typeof param === 'string') this.param = param;
    Object.freeze(this);
  }
}

